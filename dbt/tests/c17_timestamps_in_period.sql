-- C17 order timestamps within [2016-09-01, 2018-11-01); a missing purchase_ts fails.
SELECT * FROM {{ ref('fact_orders') }}
WHERE purchase_ts IS NULL
   OR purchase_ts NOT BETWEEN TIMESTAMP '2016-09-01' AND TIMESTAMP '2018-11-01' - INTERVAL 1 MICROSECOND
   OR approved_ts NOT BETWEEN TIMESTAMP '2016-09-01' AND TIMESTAMP '2018-11-01' - INTERVAL 1 MICROSECOND
   OR delivered_carrier_ts NOT BETWEEN TIMESTAMP '2016-09-01' AND TIMESTAMP '2018-11-01' - INTERVAL 1 MICROSECOND
   OR delivered_customer_ts NOT BETWEEN TIMESTAMP '2016-09-01' AND TIMESTAMP '2018-11-01' - INTERVAL 1 MICROSECOND
