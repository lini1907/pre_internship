"""Generate the dbt models from the pipeline SQL (code plan v1.1, M1).

    python dbt/sync_models.py            # write dbt/models/{staging,mart}/*.sql
    python dbt/sync_models.py --check    # exit 1 if a model is out of date

sql/staging/*.sql and sql/mart/*.sql stay the single source of the transformation logic:
each model is the same query with table names after FROM / JOIN replaced by
{{ source('raw', ...) }} (raw tables), {{ ref('stg_...') }} (staging models) or
{{ ref('category_translation_extra') }} (seed). tests/test_dbt_parity.py checks both that
the models are in sync and, when dbt is installed, that dbt builds the same mart.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from dqk.io import OLIST_FILES  # noqa: E402
from dqk.pipeline import MART_TABLES, STAGING_TABLES  # noqa: E402

MODELS = ROOT / "dbt" / "models"
SEEDS = {"category_translation_extra"}
HEADER = "-- Generated by dbt/sync_models.py from sql/{folder}/{name}.sql. Do not edit.\n"
_REF = re.compile(r"\b(FROM|JOIN)(\s+)([A-Za-z_][A-Za-z0-9_]*)\b")


def to_dbt(sql: str) -> str:
    def repl(m: re.Match) -> str:
        name = m.group(3)
        if name in OLIST_FILES:
            target = f"{{{{ source('raw', '{name}') }}}}"
        elif name in STAGING_TABLES or name in SEEDS or name in MART_TABLES:
            target = f"{{{{ ref('{name}') }}}}"
        else:  # CTE or alias
            return m.group(0)
        return f"{m.group(1)}{m.group(2)}{target}"

    body = _REF.sub(repl, sql).rstrip()
    return body[:-1].rstrip() + "\n" if body.endswith(";") else body + "\n"


def expected() -> dict[Path, str]:
    out = {}
    for folder, names in (("staging", STAGING_TABLES), ("mart", MART_TABLES)):
        for name in names:
            src = (ROOT / "sql" / folder / f"{name}.sql").read_text(encoding="utf-8")
            out[MODELS / folder / f"{name}.sql"] = (
                HEADER.format(folder=folder, name=name) + to_dbt(src)
            )
    return out


def main(argv: list[str]) -> int:
    stale = []
    for path, text in expected().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            stale.append(path)
            if "--check" not in argv:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8", newline="\n")
    if "--check" in argv:
        for p in stale:
            print(f"out of date: {p.relative_to(ROOT)}")
        return 1 if stale else 0
    print(f"wrote {len(stale)} model(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
